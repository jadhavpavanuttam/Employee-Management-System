    int pavan() {
        int employeeId = 1;
        try {
            st = con.createStatement();
            ResultSet rs = st.executeQuery("Select max(employeeId) from insertEmployee1");
            while (rs.next()) {
                employeeId = rs.getInt(employeeId);
                employeeId++;
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
        return employeeId;
    }
