    void addEmployee() throws SQLException
    {
        
        LocalDateTime ldt=LocalDateTime.now();
        DateTimeFormatter dtf=DateTimeFormatter.ofPattern(" HH : mm : ss");
        s7=dtf.format(ldt);
        jnd = JoiningDate.getDate();
        SimpleDateFormat sdf=new SimpleDateFormat("dd-MM-yyyy");
        s1 = companytype.getText();  //string
        s2 = companyname.getText();    //string        SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");
        sdf1 = sdf.format(jnd);
        s5 = Feedback.getText();    //string
        s8 = Grade.getText();    //string
        s3 = Experience.getText();  //float ->experience of years
        s4 = Salery.getText();    //double  ->salery in amoun
        s6 = TaxOnSalery.getText();
                       
        try {

            PreparedStatement ps = con.prepareStatement("INSERT into insertEmployee1 values(?,?,?,?,?,?,?,?,?,?);");
            ps.setString(1, s1);   //company  type
            ps.setString(2, s2);     //company name
            ps.setString(3, s3);  //experience
            ps.setString(4, s4);     //salery
            ps.setString(5, s5);      //feedback
            ps.setString(6, s6);   //tax
            ps.setString(7, s7);   //selected item
            ps.setString(8, s8);  //Grade
            ps.setString(9, sdf1);  //joining date
            ps.setInt(10, pavan());   //employee Id
            if (ps.executeUpdate() > 0) {
                time1.setText(s7);
//                JOptionPane.showConfirmDialog(this, "Employee Added Successfully...");
            } else {
                JOptionPane.showMessageDialog(this, "Validation Issues.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Invalid Information");
            e.printStackTrace();
        }
        finally{
        con.close();
        }

    }
